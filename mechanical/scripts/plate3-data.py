#!/usr/bin/env python3
"""Export plate 3's outline, holes, slots, standoffs and clamp holes from the layout drawing's own data
(hardware/scripts/chassis-layout.py) as OpenSCAD lists, for the compute tray preview.  Facts travel one way: the drawing is the source.

    python3 mechanical/scripts/plate3-data.py     ->  mechanical/cad/plate3-data.scad   (generated)
"""
import ast, json, os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', '..', 'hardware', 'scripts', 'chassis-layout.py')
OUT = os.path.join(HERE, '..', 'cad', 'plate3-data.scad')
NAMES = ('OUTLINE', 'HOLES', 'SLOTS', 'STANDOFFS', 'CLAMPS')

found = {}
for node in ast.parse(open(SRC).read()).body:
    if isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name) and node.targets[0].id in NAMES:
        found[node.targets[0].id] = ast.literal_eval(node.value)
with open(OUT, 'w') as f:
    f.write('// GENERATED by mechanical/scripts/plate3-data.py from hardware/scripts/chassis-layout.py. Do not edit.\n')
    for n in NAMES:
        f.write('%s = %s;\n' % (n, json.dumps(found[n])))
print({k: len(v) for k, v in found.items()}, '->', os.path.relpath(OUT))
